"""Air Quality and Forecasting API route handlers."""

from typing import Optional
from fastapi import APIRouter, Query, HTTPException, status

from app.services.aqi_service import AQIService
from app.services.model_service import ModelService
from app.schemas.aqi import AQISummary, StationResponse, ForecastResponse

router = APIRouter(prefix="/aqi", tags=["Air Quality"])


@router.get("/summary", response_model=AQISummary)
def get_aqi_summary(location: str = Query(default="Delhi NCR", min_length=2)):
    """Returns the current summary reading for a selected monitoring area."""
    try:
        summary_data = AQIService.get_demo_summary(location=location)
        return summary_data
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to generate summary: {str(e)}",
        )


@router.get("/stations", response_model=StationResponse)
def get_monitoring_stations():
    """Returns geospatial monitoring stations with current sensor levels."""
    try:
        stations = AQIService.get_demo_stations()
        return {
            "stations": stations,
            "data_status": "demo_preview",
            "is_demo_data": True,
            "count": len(stations),
        }
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to fetch stations: {str(e)}",
        )


@router.get("/forecast", response_model=ForecastResponse)
def get_aqi_forecast(
    location: str = Query(default="Delhi NCR", description="Target city or monitoring region"),
    horizon: int = Query(default=24, ge=1, le=72, description="Forward forecast horizon in hours"),
    allow_demo: bool = Query(default=True, description="Allow demo/synthetic preview output if real model is unavailable"),
):
    """Returns multi-horizon predicted AQI trajectory generated by the loaded ML model.

    Distinguishes clearly between demo synthetic previews and real-data forecasts:
    - If allow_demo is False and no real-data model is trained, returns data_status='unavailable'.
    - If allow_demo is True, returns the demo model prediction labeled with explicit disclaimers.
    """
    model_service = ModelService.get_instance()
    try:
        forecast = model_service.get_forecast(
            location=location,
            horizon_hours=horizon,
            allow_demo=allow_demo,
        )
        return forecast
    except ValueError as ve:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(ve),
        )
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Inference failure: {str(e)}",
        )
