import React from 'react';
import {
  AreaChart,
  Area,
  XAxis,
  YAxis,
  Tooltip,
  ResponsiveContainer,
  ReferenceLine,
} from 'recharts';
import { Sparkles, AlertCircle, Info } from 'lucide-react';
import { MOCK_FORECAST_24H } from '../../services/mockData';
import { DemoBadge } from '../../components/common/DemoBadge';
import { ForecastDataPoint, ForecastResponse } from '../../types/aqi';

interface ForecastChartProps {
  forecastData?: ForecastDataPoint[];
  forecastMeta?: ForecastResponse | null;
  isLoading?: boolean;
}

export const ForecastChart: React.FC<ForecastChartProps> = ({
  forecastData = MOCK_FORECAST_24H,
  forecastMeta,
  isLoading = false,
}) => {
  const isUnavailable = forecastMeta?.data_status === 'unavailable';
  const isDemo = forecastMeta?.is_demo_model ?? true;

  return (
    <div className="bg-slate-900/90 border border-slate-800 rounded-xl p-5 shadow-sm flex flex-col justify-between">
      <div>
        <div className="flex flex-wrap items-center justify-between gap-2 mb-1">
          <div className="flex items-center space-x-2">
            <Sparkles className="w-4 h-4 text-cyan-400" />
            <h3 className="text-base font-bold text-white">24h AQI Forecast</h3>
            {isDemo ? (
              <DemoBadge label="Demo Model Preview" />
            ) : (
              <span className="text-[11px] px-2 py-0.5 rounded bg-emerald-500/10 text-emerald-400 border border-emerald-500/20 font-medium">
                Verified Model
              </span>
            )}
          </div>
          <div className="flex items-center space-x-2 text-xs text-slate-400">
            <span className="flex items-center gap-1.5">
              <span className="w-2.5 h-2.5 rounded bg-cyan-500 inline-block" />
              Predicted Mean
            </span>
            <span className="flex items-center gap-1.5">
              <span className="w-2.5 h-2.5 rounded bg-cyan-500/20 inline-block border border-cyan-500/40" />
              85% Confidence Interval
            </span>
          </div>
        </div>
        <p className="text-xs text-slate-400 mb-3">
          Forward predictive projection generated by machine learning time-series regression
        </p>

        {/* Disclaimer / Model Provenance Alert */}
        <div className="mb-3 p-2.5 rounded-lg bg-slate-950/70 border border-slate-800 text-[11px] text-slate-400 flex items-start gap-2">
          <Info className="w-3.5 h-3.5 text-cyan-400 shrink-0 mt-0.5" />
          <div className="leading-relaxed">
            <strong className="text-slate-300">Model Provenance: </strong>
            {forecastMeta?.model_version ? (
              <span>
                {forecastMeta.model_version} ({forecastMeta.model_provenance || 'synthetic_fixture'})
                {forecastMeta.model_mae && ` • Test MAE: ${forecastMeta.model_mae} µg/m³`}
              </span>
            ) : (
              <span>Random Forest Regressor • Lagged PM2.5 + Cyclical Features</span>
            )}
            <div className="text-amber-400/80 text-[10px] mt-0.5">
              {forecastMeta?.disclaimer ||
                'Demo preview trained on synthetic test fixture. Not validated against real-world CPCB ground truth.'}
            </div>
          </div>
        </div>

        {/* Chart Viewport or Unavailable Message */}
        {isLoading ? (
          <div className="h-64 w-full flex items-center justify-center text-xs text-slate-500 animate-pulse">
            Loading forecast trajectory from inference service...
          </div>
        ) : isUnavailable ? (
          <div className="h-64 w-full flex flex-col items-center justify-center p-6 text-center rounded-lg bg-slate-950/40 border border-slate-800/80">
            <AlertCircle className="w-8 h-8 text-amber-400 mb-2" />
            <h4 className="text-sm font-semibold text-slate-200">Real-Data Forecast Currently Unavailable</h4>
            <p className="text-xs text-slate-400 mt-1 max-w-md">
              The pipeline architecture is operational, but real-world model deployment is awaiting verified multi-month CPCB dataset acquisition. (Refer to <code className="text-cyan-400">docs/dataset.md</code>).
            </p>
          </div>
        ) : (
          <div className="h-64 w-full">
            <ResponsiveContainer width="100%" height="100%">
              <AreaChart
                data={forecastData}
                margin={{ top: 10, right: 10, left: -20, bottom: 0 }}
              >
                <defs>
                  <linearGradient id="forecastFill" x1="0" y1="0" x2="0" y2="1">
                    <stop offset="5%" stopColor="#06b6d4" stopOpacity={0.4} />
                    <stop offset="95%" stopColor="#06b6d4" stopOpacity={0.0} />
                  </linearGradient>
                  <linearGradient id="boundsFill" x1="0" y1="0" x2="0" y2="1">
                    <stop offset="5%" stopColor="#0891b2" stopOpacity={0.15} />
                    <stop offset="95%" stopColor="#0891b2" stopOpacity={0.05} />
                  </linearGradient>
                </defs>
                <XAxis
                  dataKey="time"
                  stroke="#64748b"
                  fontSize={11}
                  tickLine={false}
                  axisLine={{ stroke: '#334155' }}
                />
                <YAxis
                  stroke="#64748b"
                  fontSize={11}
                  tickLine={false}
                  axisLine={{ stroke: '#334155' }}
                  domain={[100, 350]}
                />
                <Tooltip
                  content={({ active, payload, label }) => {
                    if (active && payload && payload.length) {
                      const data = payload[0].payload;
                      return (
                        <div className="bg-slate-950/95 border border-slate-700/80 p-2.5 rounded-lg text-xs shadow-xl backdrop-blur">
                          <div className="font-semibold text-slate-200 mb-1">{label}</div>
                          <div className="text-cyan-400 font-mono font-bold">
                            Predicted AQI: {data.predictedAqi}
                          </div>
                          {data.predictedPm25 && (
                            <div className="text-slate-300 text-[11px]">
                              PM2.5: {data.predictedPm25} µg/m³
                            </div>
                          )}
                          <div className="text-slate-400 text-[11px] mt-0.5">
                            Range: {data.lowerBound} - {data.upperBound}
                          </div>
                          <div className="text-amber-400 font-medium text-[11px] mt-1">
                            Category: {data.category}
                          </div>
                        </div>
                      );
                    }
                    return null;
                  }}
                />
                <ReferenceLine
                  y={300}
                  stroke="#ef4444"
                  strokeDasharray="3 3"
                  label={{
                    value: 'Severe (300)',
                    fill: '#ef4444',
                    fontSize: 10,
                    position: 'insideTopRight',
                  }}
                />
                <ReferenceLine
                  y={200}
                  stroke="#f97316"
                  strokeDasharray="3 3"
                  label={{
                    value: 'Poor (200)',
                    fill: '#f97316',
                    fontSize: 10,
                    position: 'insideTopRight',
                  }}
                />
                <Area
                  type="monotone"
                  dataKey="upperBound"
                  stroke="transparent"
                  fill="url(#boundsFill)"
                />
                <Area
                  type="monotone"
                  dataKey="predictedAqi"
                  stroke="#06b6d4"
                  strokeWidth={2.5}
                  fill="url(#forecastFill)"
                />
              </AreaChart>
            </ResponsiveContainer>
          </div>
        )}
      </div>

      <div className="text-[10px] text-slate-500 pt-3 border-t border-slate-800/60 mt-4 flex items-center justify-between">
        <span>Model: Random Forest Regressor (Auto-regressive + Cyclical)</span>
        <span>Forecast Horizon: +24h</span>
      </div>
    </div>
  );
};
